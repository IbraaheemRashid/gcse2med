import fs from 'node:fs';
import path from 'node:path';

// The supplied banks and study engines remain the source of truth. Generate
// isolated ES modules, not executable HTML pages or an iframe.
const root = process.cwd();
const out = path.join(root, 'public/learning-tools');
fs.mkdirSync(out, {recursive:true});
const entries = ['biology','chemistry','physics'].map(s=>[`${s}-flashcards`,`public/resources/flashcards/${s}.html`]);
entries.push(['maths-generator','public/resources/tools/maths-question-generator.html']);
for(const s of ['biology','chemistry','physics','maths']) entries.push([`${s}-assessment`,`public/assessments/${s}.html`]);
for(const [id,file] of entries) {
  const html=fs.readFileSync(path.join(root,file),'utf8');
  let body=html.match(/<body[^>]*>([\s\S]*?)<\/body>/i)[1].replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'');
  body=body.replace(/<nav\b[\s\S]*?<\/nav>/gi,'').replace(/<footer class="sitefooter">[\s\S]*?<\/footer>/gi,'')
    .replace(/<a class="skip-link"[^>]*>[\s\S]*?<\/a>/g,'')
    .replace(/<img\b[^>]*class="logo-[ld]"[^>]*>/g,'')
    .replace(/<h1\b/g,'<h2').replace(/<\/h1>/g,'</h2>')
    .replace(/<main\b/g,'<div').replace(/<\/main>/g,'</div>');
  let css=[...html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)].map(m=>m[1]).join('\n');
  css=css.replace(/:root/g,'.tool-document').replace(/\bhtml(?=[\s.{:#>,\[])/g,'.tool-document').replace(/\bbody(?=[\s.{:#>,\[])/g,'.tool-body');
  let code=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].at(-1)[1];
  code=code.replace("t=__LS.getItem('g2m-theme')", "t='light'");
  // Generated headings sit below the native page's single h1.
  code=code.replace(/(['"])h1\1/g,"'h2'").replace(/<h1\b/g,'<h2').replace(/<\/h1>/g,'</h2>');
  const generatedModule=`// Generated by scripts/build-learning-tools.mjs. Edit source banks, not this file.\nexport const markup=${JSON.stringify(body)};\nexport const styles=${JSON.stringify(css)};\nexport function mount(document,window,setTimeout,setInterval,clearTimeout,clearInterval,requestAnimationFrame,cancelAnimationFrame,MutationObserver,history,matchMedia){\n${code}\n}\n`;
  fs.writeFileSync(path.join(out,id+'.js'),generatedModule);
  console.log(id, 'generated');
}
